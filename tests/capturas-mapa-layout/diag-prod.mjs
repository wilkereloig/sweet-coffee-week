import { chromium } from 'playwright'
const nav = await chromium.launch()
const ctx = await nav.newContext({ viewport: { width: 1440, height: 900 } })
await ctx.addInitScript((c) => { localStorage.setItem('scw_privacidade', c) }, JSON.stringify({ v: 1, analise: false, em: Date.now(), ate: Date.now() + 1e10 }))
const page = await ctx.newPage()
await page.goto('https://sweetcoffeeweek.com.br/cartoon/mapa', { waitUntil: 'networkidle', timeout: 120000 })
await page.getByRole('button', { name: /Mapa real/ }).first().click()
await page.waitForTimeout(500)
await page.getByRole('button', { name: /no mapa/i }).first().click().catch(() => {})
await page.waitForTimeout(7000)
console.log('google?', await page.locator('.gm-style').count(), 'pins', await page.locator('.ct-marcador--pin').count())
const pin = page.locator('.ct-marcador--pin').first()
await pin.scrollIntoViewIfNeeded()
const bb = await pin.boundingBox()
await page.mouse.move(bb.x + bb.width / 2, bb.y + bb.height / 2, { steps: 3 }); await page.mouse.down(); await page.waitForTimeout(100); await page.mouse.up()
await page.waitForTimeout(1500)
console.log('sel', await page.locator('.ct-marcador--pin.is-sel').count())
await nav.close()
