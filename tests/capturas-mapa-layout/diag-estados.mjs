import { chromium } from 'playwright'
const BASE = 'http://localhost:5212'
const nav = await chromium.launch()
async function abrir (v) {
  const ctx = await nav.newContext({ viewport: { width: v.w, height: v.h }, hasTouch: !!v.t, isMobile: !!v.t, deviceScaleFactor: v.t ? 2 : 1 })
  await ctx.addInitScript((c) => { localStorage.setItem('scw_privacidade', c) }, JSON.stringify({ v: 1, analise: false, em: Date.now(), ate: Date.now() + 1e10 }))
  await ctx.route('**/tiles.openfreemap.org/**', (r) => r.abort('failed'))
  const page = await ctx.newPage()
  await page.goto(`${BASE}/cartoon/mapa?preview=1`, { waitUntil: 'networkidle', timeout: 120000 })
  await page.locator('.ct-mundo__casa:not(.is-agrupado)').first().waitFor({ timeout: 30000 })
  await page.waitForTimeout(800)
  return { ctx, page }
}
const shot = (page, n) => page.screenshot({ path: `tests/capturas-mapa-layout/${n}.png` })
// celular
let { ctx, page } = await abrir({ n: 'celular', w: 390, h: 844, t: true })
await page.evaluate(() => document.querySelector('.ct-mapa__moldura').scrollIntoView({ block: 'start' }))
await page.waitForTimeout(500)
await page.locator('.ct-mundo__casa').nth(6).click({ force: true })
await page.waitForTimeout(700)
await shot(page, 'cel-casa-escolhida')
await page.keyboard.press('Escape')
await page.getByRole('button', { name: /Minha rota/ }).first().click().catch(() => {})
await page.waitForTimeout(600)
await shot(page, 'cel-minha-rota')
await page.keyboard.press('Escape')
await page.waitForTimeout(300)
await page.locator('.ct-mapa__ampliar').first().click().catch(() => {})
await page.waitForTimeout(900)
await shot(page, 'cel-tela-cheia')
await ctx.close()
// desktop
;({ ctx, page } = await abrir({ n: 'desktop', w: 1440, h: 900 }))
await page.evaluate(() => document.querySelector('.ct-mapa__moldura').scrollIntoView({ block: 'start' }))
await page.locator('.ct-mundo__casa').nth(3).click({ force: true })
await page.waitForTimeout(800)
await shot(page, 'desk-casa-escolhida')
await page.locator('.ct-mapa__ampliar').first().click().catch(() => {})
await page.waitForTimeout(900)
await shot(page, 'desk-tela-cheia')
await ctx.close()
await nav.close()
