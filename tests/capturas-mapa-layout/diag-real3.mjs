import { chromium } from 'playwright'
const nav = await chromium.launch()
const ctx = await nav.newContext({ viewport: { width: 1440, height: 900 } })
await ctx.addInitScript((c) => { localStorage.setItem('scw_privacidade', c) }, JSON.stringify({ v: 1, analise: false, em: Date.now(), ate: Date.now() + 1e10 }))
const page = await ctx.newPage()
page.on('console', (m) => { if (m.type() === 'error') console.log('console.error', m.text().slice(0, 200)) })
page.on('pageerror', (e) => console.log('pageerror', String(e.message).slice(0, 200)))
await page.goto('http://localhost:5212/cartoon/mapa?preview=1', { waitUntil: 'networkidle', timeout: 120000 })
await page.getByRole('button', { name: /Mapa real/ }).first().click()
await page.waitForTimeout(500)
await page.getByRole('button', { name: /no mapa/i }).first().click().catch(() => {})
await page.waitForTimeout(6000)
await page.evaluate(() => document.querySelector('.ct-mapa__moldura')?.scrollIntoView({ block: 'start' }))
const z = () => page.evaluate(() => { const t = [...document.querySelectorAll('.gm-style img')].map((i) => i.src.match(/!1i(\d+)/)?.[1]).filter(Boolean); return t.length ? Math.max(...t.map(Number)) : null })
console.log('zoom tiles antes', await z())
await page.evaluate(() => document.querySelector('.ct-selo-grupo').click())
await page.waitForTimeout(3000)
console.log('zoom tiles depois (JS click)', await z(), 'selos', await page.locator('.ct-selo-grupo').count())
await page.screenshot({ path: 'tests/capturas-mapa-layout/real-desktop-jsclick.png' })
await nav.close()
