import { chromium } from 'playwright'
const nav = await chromium.launch()
const ctx = await nav.newContext({ viewport: { width: 1440, height: 900 } })
await ctx.addInitScript((c) => { localStorage.setItem('scw_privacidade', c) }, JSON.stringify({ v: 1, analise: false, em: Date.now(), ate: Date.now() + 1e10 }))
const page = await ctx.newPage()
const msgs = []
page.on('console', (m) => { if (/Focusable|AdvancedMarker/i.test(m.text())) msgs.push(m.text().slice(0, 160)) })
await page.goto('http://localhost:5212/cartoon/mapa?preview=1', { waitUntil: 'networkidle', timeout: 120000 })
await page.getByRole('button', { name: /Mapa real/ }).first().click()
await page.waitForTimeout(500)
await page.getByRole('button', { name: /no mapa/i }).first().click().catch(() => {})
await page.waitForTimeout(6000)
await page.locator('.ct-selo-grupo').first().click({ force: true })
await page.waitForTimeout(2500)
console.log('marcadores', await page.evaluate(() => [...document.querySelectorAll('gmp-advanced-marker')].slice(0, 40).filter((m) => m.querySelector('.ct-marcador--pin')).slice(0, 2).map((m) => ({ role: m.getAttribute('role'), tab: m.getAttribute('tabindex'), label: m.getAttribute('aria-label'), pressed: m.getAttribute('aria-pressed') }))))
// teclado: foca o 1º marcador de pin e aperta Enter
const alvo = page.locator('gmp-advanced-marker:has(.ct-marcador--pin:not(.is-agrupado))').first()
await alvo.focus()
await page.keyboard.press('Enter')
await page.waitForTimeout(1200)
console.log('sel por teclado', await page.locator('.ct-marcador--pin.is-sel').count(), 'cartao', await page.locator('.ct-folha-m--casa').count())
console.log('avisos do Google:', JSON.stringify(msgs))
await nav.close()
