import { chromium } from 'playwright'
const nav = await chromium.launch()
const ctx = await nav.newContext({ viewport: { width: 1440, height: 900 } })
await ctx.addInitScript((c) => { localStorage.setItem('scw_privacidade', c) }, JSON.stringify({ v: 1, analise: false, em: Date.now(), ate: Date.now() + 1e10 }))
const page = await ctx.newPage()
await page.goto('http://localhost:5212/cartoon/mapa?preview=1', { waitUntil: 'networkidle', timeout: 120000 })
await page.getByRole('button', { name: /Mapa real/ }).first().click()
await page.waitForTimeout(500)
await page.getByRole('button', { name: /no mapa/i }).first().click().catch(() => {})
await page.waitForTimeout(6000)
await page.evaluate(() => document.querySelector('.ct-mapa__moldura')?.scrollIntoView({ block: 'start' }))
await page.locator('.ct-selo-grupo').first().click({ force: true })
await page.waitForTimeout(2500)
const pin = page.locator('.ct-marcador--pin:not(.is-agrupado)').nth(2)
const bb = await pin.boundingBox()
console.log('bb', JSON.stringify(bb))
await page.evaluate(() => { window.__ev = []; const el = document.querySelectorAll('.ct-marcador--pin:not(.is-agrupado)')[2]; for (const t of ['pointerdown','pointerup','mousedown','mouseup','click']) el.addEventListener(t, (e) => window.__ev.push(t + '@' + Math.round(performance.now()))); new MutationObserver(() => window.__ev.push('cls:' + el.className + '@' + Math.round(performance.now()))).observe(el, { attributes: true }) })
await page.mouse.click(bb.x + bb.width / 2, bb.y + bb.height / 2)
await page.waitForTimeout(1500)
console.log('eventos', JSON.stringify(await page.evaluate(() => window.__ev)))
console.log('sel', await page.locator('.ct-marcador--pin.is-sel').count(), await page.locator('.ct-folha-m--casa').count())
await page.screenshot({ path: 'tests/capturas-mapa-layout/real-selecao.png' })
await nav.close()
